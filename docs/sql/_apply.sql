-- BACKUP SCHEMA - CREATE.sql
-- backup_schema() -> the full structure of the database as one SQL script (sequences, tables, keys, indexes,
-- views, functions, triggers, row level security policies, grants). Saved as _schema.sql in every backup zip,
-- so the database can be rebuilt on a new Supabase project. Admin / mailer only.
-- Undo with: BACKUP SCHEMA - REVERT.sql
create or replace function public.backup_schema() returns text
language plpgsql stable security definer set search_path to 'public' as $$
declare o text := '-- MAHRJAN SYSTEM - DATABASE STRUCTURE' || chr(10) || '-- generated ' || to_char(now() at time zone 'Asia/Dubai', 'YYYY-MM-DD HH24:MI') || ' (Dubai)' || chr(10) || 'set check_function_bodies = off;' || chr(10) || chr(10);
  r record; cols text;
begin
  if not public.backup_allowed() then raise exception 'Only the admin can take a backup.'; end if;
  -- sequences not created by identity columns
  for r in select c.relname from pg_class c join pg_namespace n on n.oid = c.relnamespace
           where n.nspname = 'public' and c.relkind = 'S'
             and not exists (select 1 from pg_depend d where d.objid = c.oid and d.deptype = 'i') order by 1 loop
    o := o || format('create sequence if not exists public.%I;', r.relname) || chr(10); end loop;
  -- tables
  for r in select c.oid, c.relname, c.relrowsecurity from pg_class c join pg_namespace n on n.oid = c.relnamespace
           where n.nspname = 'public' and c.relkind = 'r' order by 1 loop
    select string_agg(format('  %I %s', a.attname, format_type(a.atttypid, a.atttypmod))
             || case when a.attidentity = 'a' then ' generated always as identity' when a.attidentity = 'd' then ' generated by default as identity' else '' end
             || case when a.attgenerated = 's' then ' generated always as (' || pg_get_expr(ad.adbin, ad.adrelid) || ') stored'
                     when ad.adbin is not null then ' default ' || pg_get_expr(ad.adbin, ad.adrelid) else '' end
             || case when a.attnotnull then ' not null' else '' end, ',' || chr(10) order by a.attnum)
      into cols from pg_attribute a left join pg_attrdef ad on ad.adrelid = a.attrelid and ad.adnum = a.attnum
      where a.attrelid = r.oid and a.attnum > 0 and not a.attisdropped;
    o := o || format('create table public.%I (', r.relname) || chr(10) || cols || chr(10) || ');' || chr(10);
    if r.relrowsecurity then o := o || format('alter table public.%I enable row level security;', r.relname) || chr(10); end if;
  end loop;
  -- primary / unique / check keys first, then foreign keys
  for r in select format('alter table public.%I add constraint %I %s;', c.relname, k.conname, pg_get_constraintdef(k.oid)) s
           from pg_constraint k join pg_class c on c.oid = k.conrelid join pg_namespace n on n.oid = c.relnamespace
           where n.nspname = 'public' and k.contype in ('p','u','c','x') order by k.contype <> 'p', c.relname, k.conname loop
    o := o || r.s || chr(10); end loop;
  for r in select format('alter table public.%I add constraint %I %s;', c.relname, k.conname, pg_get_constraintdef(k.oid)) s
           from pg_constraint k join pg_class c on c.oid = k.conrelid join pg_namespace n on n.oid = c.relnamespace
           where n.nspname = 'public' and k.contype = 'f' order by c.relname, k.conname loop
    o := o || r.s || chr(10); end loop;
  -- other indexes
  for r in select pg_get_indexdef(i.indexrelid) || ';' s from pg_index i join pg_class c on c.oid = i.indrelid join pg_namespace n on n.oid = c.relnamespace
           where n.nspname = 'public' and not exists (select 1 from pg_constraint k where k.conindid = i.indexrelid) order by 1 loop
    o := o || r.s || chr(10); end loop;
  o := o || chr(10) || '-- functions' || chr(10);
  for r in select pg_get_functiondef(p.oid) || ';' s from pg_proc p join pg_namespace n on n.oid = p.pronamespace
           where n.nspname = 'public' and p.prokind in ('f','p')
             and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e') order by p.proname loop
    o := o || r.s || chr(10) || chr(10); end loop;
  o := o || '-- views' || chr(10);
  for r in select format('create or replace view public.%I%s as %s', c.relname,
                    case when c.reloptions is not null then ' with (' || array_to_string(c.reloptions, ', ') || ')' else '' end, pg_get_viewdef(c.oid)) s
           from pg_class c join pg_namespace n on n.oid = c.relnamespace where n.nspname = 'public' and c.relkind = 'v' order by c.oid loop
    o := o || r.s || chr(10); end loop;
  o := o || chr(10) || '-- triggers' || chr(10);
  for r in select pg_get_triggerdef(t.oid) || ';' s from pg_trigger t join pg_class c on c.oid = t.tgrelid join pg_namespace n on n.oid = c.relnamespace
           where n.nspname = 'public' and not t.tgisinternal order by c.relname, t.tgname loop
    o := o || r.s || chr(10); end loop;
  o := o || chr(10) || '-- row level security policies' || chr(10);
  for r in select format('create policy %I on public.%I as %s for %s to %s%s%s;', policyname, tablename, permissive, cmd, array_to_string(roles, ', '),
                    case when qual is not null then ' using (' || qual || ')' else '' end,
                    case when with_check is not null then ' with check (' || with_check || ')' else '' end) s
           from pg_policies where schemaname = 'public' order by tablename, policyname loop
    o := o || r.s || chr(10); end loop;
  o := o || chr(10) || '-- grants' || chr(10);
  for r in select format('grant %s on public.%I to %I;', string_agg(privilege_type, ', ' order by privilege_type), table_name, grantee) s
           from information_schema.role_table_grants where table_schema = 'public' and grantee in ('anon','authenticated','service_role')
           group by table_name, grantee order by 1 loop
    o := o || r.s || chr(10); end loop;
  for r in select format('revoke all on function public.%I(%s) from public, anon; grant execute on function public.%I(%s) to authenticated;',
                    p.proname, pg_get_function_identity_arguments(p.oid), p.proname, pg_get_function_identity_arguments(p.oid)) s
           from pg_proc p join pg_namespace n on n.oid = p.pronamespace
           where n.nspname = 'public' and p.prokind = 'f' and has_function_privilege('authenticated', p.oid, 'execute') and not has_function_privilege('anon', p.oid, 'execute') order by 1 loop
    o := o || r.s || chr(10); end loop;
  return o;
end $$;
revoke all on function public.backup_schema() from public, anon;
grant execute on function public.backup_schema() to authenticated;
select length(pg_get_functiondef('public.backup_schema'::regproc)) as created;
